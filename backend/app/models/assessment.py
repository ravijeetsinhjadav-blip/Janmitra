import uuid
from sqlalchemy import Column, String, Float, DateTime, ForeignKey, func
from sqlalchemy.dialects.postgresql import UUID, JSONB
from sqlalchemy.orm import relationship
from app.core.database import Base


class Assessment(Base):
    """AI-powered eligibility assessment and document readiness evaluation.
    
    Advisory Disclaimer:
    Assessment results generated by JanMitra Assist are advisory evaluations
    based on user-supplied criteria and document extraction. They do NOT constitute
    official government determinations or formal approvals.
    """
    __tablename__ = "assessments"

    id = Column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        index=True,
        comment="Primary UUID key for assessment run",
    )
    user_id = Column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
        comment="Citizen user ID evaluated in this assessment",
    )
    scheme_id = Column(
        UUID(as_uuid=True),
        ForeignKey("schemes.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
        comment="Target scheme evaluated (null if generalized readiness assessment)",
    )
    assessment_type = Column(
        String(50),
        nullable=False,
        default="scheme_eligibility",
        index=True,
        comment="Assessment category: scheme_eligibility, document_readiness, or profile_gap",
    )
    result_data = Column(
        JSONB,
        nullable=False,
        default=dict,
        comment="Structured advisory outcome (missing docs, rule matches, AI recommendations) stored as JSONB",
    )
    overall_readiness_score = Column(
        Float,
        nullable=True,
        comment="Readiness score ranging from 0.0 to 100.0 (nullable)",
    )
    created_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
        comment="Timestamp when assessment was generated",
    )

    # Relationships
    user = relationship("User", back_populates="assessments")
    scheme = relationship("Scheme", back_populates="assessments")

    def __repr__(self) -> str:
        return f"<Assessment id={self.id} user_id={self.user_id} score={self.overall_readiness_score}>"
