from uuid import UUID
from datetime import datetime
from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field
from app.schemas.subscription import CitizenSubscriptionResponse


class RazorpayOrderCreateRequest(BaseModel):
    """Payload to initiate a secure Razorpay order."""
    plan_type: str = Field(default="premium", description="Subscription tier: must be 'premium'")
    billing_cycle: str = Field(..., description="Billing cycle: 'monthly' or 'yearly'")


class RazorpayOrderResponse(BaseModel):
    """Secure Razorpay order details returned for client checkout."""
    order_id: str = Field(..., description="Razorpay order identifier (e.g. order_xxx)")
    amount: int = Field(..., description="Amount in smallest currency unit (paise)")
    amount_inr: float = Field(..., description="Amount in INR (e.g. 99.00 or 799.00)")
    currency: str = Field(default="INR", description="Payment currency code")
    key_id: str = Field(..., description="Razorpay public Key ID for client checkout")
    plan_type: str
    billing_cycle: str
    is_dev_mode: bool = False


class PaymentVerificationRequest(BaseModel):
    """Payload to cryptographically verify Razorpay client payment outcome."""
    razorpay_order_id: str = Field(..., description="Razorpay Order ID")
    razorpay_payment_id: str = Field(..., description="Razorpay Payment ID")
    razorpay_signature: str = Field(..., description="HMAC-SHA256 signature generated by Razorpay")
    payment_method: Optional[str] = Field(default=None, description="Payment instrument used: upi, card, qr, etc.")


class PaymentVerificationResponse(BaseModel):
    """Outcome of server-side cryptographic payment verification."""
    success: bool
    message: str
    transaction_id: UUID
    subscription: CitizenSubscriptionResponse


class PaymentTransactionResponse(BaseModel):
    """Summary of a recorded payment transaction."""
    id: UUID
    razorpay_order_id: str
    razorpay_payment_id: Optional[str] = None
    amount: float
    currency: str
    plan_type: str
    billing_cycle: str
    payment_status: str
    amount_refunded: float = 0.0
    dispute_status: str = "none"
    payment_method: Optional[str] = None
    error_code: Optional[str] = None
    error_description: Optional[str] = None
    created_at: datetime


class PaymentHistoryResponse(BaseModel):
    """List of citizen's past payment transactions."""
    total: int
    items: List[PaymentTransactionResponse]
